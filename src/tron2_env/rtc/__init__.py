"""Tron2 双机械臂的低延迟动作流式执行辅助工具：Real-Time Chunking (RTC)。

================================================================================
给新手的快速导读
================================================================================

1. 这个包是做什么的？
   ----------------------------------------------------------------------
   它和 ``env.py`` / ``motion/`` 一样属于"可选增强层"，本文件本身**不实现任何
   逻辑**，只是把包内两个工具类重新导出成统一入口（门面 / facade 模式），
   与顶层的 ``tron2_env/__init__.py`` 思路完全一致，只是规模更小。

   RTC（Real-Time Chunking，实时分块）来自 LeRobot / “Learning to Act from
   Action Chunks” 系列工作的思想：策略模型不是一帧一帧地输出动作，而是一次性
   预测"未来 T 个时间步的动作块（chunk）"。本包就负责管理这些动作块，
   让机器人能在**不等待下一次推理**的情况下连续执行动作，从而降低端到端延迟。

   本包包含两个相互配合的组件：

     * ``ActionQueue``     —— 动作块队列。存放策略输出的动作序列，供控制线程
                              逐帧取用；支持"RTC 模式"（新推理结果直接覆盖整条
                              队列，并按推理延迟对齐）与"非 RTC 模式"（新结果
                              追加到队列尾部，保持连续）。
     * ``LatencyTracker``  —— 推理延迟统计器。记录最近若干次推理的耗时，提供
                              max / p50 / p95 等查询，用于监控与调优。

2. 这个 __init__.py 到底做了什么？
   ----------------------------------------------------------------------
   Python 里导入一个"目录包"时，会先执行目录下的 ``__init__.py``。这里做两件事：

     a) 用**相对导入** ``from .action_queue import ActionQueue`` 把子模块中
        定义好的类"引上来"，这样用户只需要写：
            from tron2_env.rtc import ActionQueue
        而不必写：
            from tron2_env.rtc.action_queue import ActionQueue
        好处是：公共 API 一目了然；将来重排内部文件结构时，
        只要保持这里导出的名字不变，用户代码就不用改。

     b) 通过 ``__all__`` 声明"公开 API 清单"，作用有两个：
            - 控制 ``from tron2_env.rtc import *`` 会导入哪些名字；
            - 给 IDE / 文档工具一份"官方公开接口"的索引。
        新手可以把 ``__all__`` 当作本包唯一的"对外承诺"：
        列表里的名字可以放心用，没列出来的属于内部实现细节。

3. 一个最简使用场景（串起来理解）
   ----------------------------------------------------------------------
       queue = ActionQueue(rtc_enabled=True)      # 开 RTC 模式
       tracker = LatencyTracker(maxlen=100)        # 保留最近 100 次延迟

       # 每收到一次策略输出，就 merge 进去（RTC 会按推理延迟截掉旧帧再替换）
       queue.merge(original_actions, processed_actions, real_delay=infer_delay)

       # 控制线程在固定频率下逐帧取动作：
       while (act := queue.get()) is not None:
           send_to_robot(act)

    两个类不直接互相引用：queue 负责"动作流"，tracker 负责"延迟指标"，
    它们通过共同的调用方（如 Tron2Env / 策略推理循环）在时序上协作。

================================================================================
"""

